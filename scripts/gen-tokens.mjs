// T9.1 (FR-LOOK-003): DESIGN.md `sirkov-tokens` → sirtone.css + tokens.generated.ts.
// `pnpm --filter @sirtone/desktop gen:tokens` writes the files; the test in
// apps/desktop/src/shared/lib/tokens.test.ts fails when they drift from DESIGN.md.
// Fabric (`color.fabric`, `glass.fabricOnly`) is read but not emitted: removed by D-155.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { generateAccentSetWith } from "../apps/desktop/src/shared/lib/colorMath.ts";

const root = new URL("../", import.meta.url);
const DESIGN = new URL("DESIGN.md", root);
const SEEDS = new URL("apps/desktop/src/shared/theme/accentSeeds.json", root);
export const OUT_CSS = new URL("apps/desktop/src/shared/ui/tokens/sirtone.css", root);
export const OUT_TS = new URL("apps/desktop/src/shared/ui/tokens/tokens.generated.ts", root);

/** The JSON block of DESIGN.md §2. */
export function parseTokens(md) {
  const m = /```json sirkov-tokens\r?\n([\s\S]*?)\r?\n```/.exec(md);
  if (!m) throw new Error("DESIGN.md: block `json sirkov-tokens` not found");
  return JSON.parse(m[1]);
}

/** token name → CSS variable (names kept from the earlier sirtone.css: DESIGN.md §4 «Имя в Fabric»). */
const NEUTRAL_VARS = [
  ["bg-base", "bg"],
  ["bg-layer", "surface"],
  ["bg-raised", "raised"],
  ["bg-flyout", "flyout"],
  ["text-primary", "text"],
  // Q-32: the file has two text levels; `text-tertiary` is `textMuted` too.
  ["text-secondary", "textMuted"],
  ["text-tertiary", "textMuted"],
  ["icon", "textMuted"],
  ["border", "line"],
  ["separator", "line"],
  ["focus-ring", "text"],
  ["danger", "danger"],
  ["success", "success"],
  ["warning", "warning"],
  ["primary", "primary"],
  ["primary-text", "primaryText"],
  ["on-primary", "onPrimary"],
];
const ACCENT_VARS = [
  ["accent-fill", "accent"],
  ["accent-text", "accentText"],
  ["accent-on", "onAccent"],
];

/** Derived from tokens only (no new hex): hover/selected/inactive/placeholder (Q-32, docs/06 §12). */
const DERIVED = `  --bg-hover: color-mix(in srgb, var(--text-primary) 6%, transparent);
  --bg-selected: var(--primary);
  --inactive: color-mix(in srgb, var(--text-secondary) 60%, var(--bg-base));
  --artwork-placeholder: var(--bg-flyout);`;

const themeBlock = (sel, c, extra = "") => {
  const body = NEUTRAL_VARS.map(([v, k]) => `  --${v}: ${c[k].toLowerCase()};`).join("\n");
  return `${sel} {\n${body}${extra}\n}\n`;
};

const accentLines = (set) =>
  `  --accent-fill: ${set.accentFill};\n  --accent-text: ${set.accentText};\n  --accent-on: ${set.accentOn};`;

export function slugs(seeds) {
  return ["sirkov", ...Object.keys(seeds).filter((k) => !k.startsWith("_"))];
}

/** The 17 sets × 2 themes: `sirkov` from the tokens, the rest recomputed against the new surfaces (T9.3). */
export function buildAccentSets(t, seeds) {
  const ctx = {
    backgrounds: {
      dark: ["bg", "surface", "raised", "flyout"].map((k) => t.color.dark[k]),
      light: ["bg", "surface", "raised", "flyout"].map((k) => t.color.light[k]),
    },
    inkDark: t.color.light.text,
    inkLight: t.color.dark.onAccent,
  };
  const sets = {};
  for (const slug of slugs(seeds)) {
    sets[slug] = {};
    for (const theme of ["dark", "light"]) {
      const c = t.color[theme];
      sets[slug][theme] =
        slug === "sirkov"
          ? {
              accentFill: c.accent.toLowerCase(),
              accentText: c.accentText.toLowerCase(),
              accentOn: c.onAccent.toLowerCase(),
            }
          : generateAccentSetWith(seeds[slug][theme], theme, ctx);
    }
  }
  return { ctx, sets };
}

export function build(md, seeds) {
  const t = parseTokens(md);
  const { ctx, sets } = buildAccentSets(t, seeds);
  const c = t.color;
  const px = (n) => `${n}px`;
  const sp = t.space.steps.map((s) => [s, s * t.space.unit]);
  const spaceName = (s) => String(s).replace(".", "-");
  const ty = t.type.styles;
  const style = (n, cls) =>
    `.${cls} {\n  font: ${ty[n].weight} ${px(ty[n].size)} / ${px(ty[n].line)} var(--font-sans);\n}\n`;

  let css = `/* GENERATED by scripts/gen-tokens.mjs from the \`sirkov-tokens\` block of DESIGN.md (T9.1, FR-LOOK-003).
   Do not edit: change DESIGN.md (owner's file) or the script, then \`pnpm --filter @sirtone/desktop gen:tokens\`.
   Variable names follow the «Имя в Fabric» column of DESIGN.md §4 so components keep working. */
@font-face {
  font-family: "${t.font.body}";
  src: url("../../../assets/fonts/${t.font.body}-Variable.ttf") format("truetype");
  font-weight: 100 900;
  font-display: block;
}

:root {
  --font-sans: ${t.font.body}, "Segoe UI Variable Text", "Segoe UI", system-ui, sans-serif;
  /* spacing (space.unit × space.steps) */
${sp.map(([s, v]) => `  --space-${spaceName(s)}: ${px(v)};`).join("\n")}
  /* radius */
  --radius-xs: ${px(t.radius.xs)};
  --radius-sm: ${px(t.radius.sm)};
  --radius-md: ${px(t.radius.md)};
  --radius-lg: ${px(t.radius.lg)};
  --radius-xl: ${px(t.radius.xl)};
  --radius-window-plain: ${px(t.radius.windowPlain)};
  --radius-full: ${px(t.radius.full)};
  /* frame, control, icon */
  --titlebar-height: ${px(t.frame.header)};
  --sidebar-width: ${px(t.frame.sidebar)};
  --sidebar-collapsed: ${px(t.frame.sidebarCollapsed)};
  --player-height: ${px(t.frame.player)};
  --row-height: ${px(t.frame.trackRow)};
  --nav-row-height: ${px(t.frame.navRow)};
  --artwork-card: ${px(t.frame.albumCard)};
  --button-height: ${px(t.control.md)};
  --chip-height: ${px(t.control.sm)};
  --play-size: ${px(t.control.lg)};
  --control-stroke: ${px(t.control.stroke)};
  --focus-width: ${px(t.control.focus)};
  --icon-size: ${px(t.icon.md)};
  --icon-stroke: ${t.icon.stroke};
  --tap-web: ${px(t.tap.web)};
  /* motion */
  --ease-out: ${t.motion.ease};
  --dur-fast: ${t.motion.fast}ms;
  --dur-base: ${t.motion.base}ms;
  --dur-theme: ${t.motion.slow}ms;
  /* elevation: blur levels, alpha per theme (offsets are not in the file: docs/10 §7) */
  --shadow-flyout: 0 8px ${px(t.elevation.blur[5])} rgb(0 0 0 / var(--shadow-alpha));
  --shadow-artwork: 0 2px ${px(t.elevation.blur[4])} rgb(0 0 0 / var(--shadow-alpha));
}

/* Neutrals: dark by default */
`;
  css += themeBlock(
    ':root,\n[data-theme="dark"]',
    c.dark,
    `\n  --shadow-alpha: ${t.elevation.alphaDark};\n${DERIVED}\n  --artwork-scrim: rgb(0 0 0 / 0.45);`,
  );
  css += `\n${themeBlock(
    '[data-theme="light"]',
    c.light,
    `\n  --shadow-alpha: ${t.elevation.alphaLight};\n${DERIVED}\n  --artwork-scrim: rgb(0 0 0 / 0.45);`,
  )}`;
  // High contrast (lightHC / darkHC): the system setting sets data-contrast="more" (theme.ts).
  css += `\n/* Повышенная контрастность: lightHC / darkHC */\n`;
  css += themeBlock('[data-theme="light"][data-contrast="more"]', c.lightHC);
  css += themeBlock('[data-theme="dark"][data-contrast="more"]', c.darkHC);

  css += `\n/* Accent: Sir.kov (#650A12) by default; the 17 sets are recomputed against these surfaces (T9.3) */\n`;
  for (const theme of ["dark", "light"]) {
    const s = sets.sirkov[theme];
    const sel = theme === "dark" ? `:root,\n[data-theme="dark"]` : `[data-theme="light"]`;
    css += `${sel} {\n${accentLines(s)}\n}\n`;
  }
  // HC: the accent text is the file's own HC value.
  css += `[data-theme="light"][data-contrast="more"] {\n  --accent-text: ${c.lightHC.accentText.toLowerCase()};\n}\n`;
  css += `[data-theme="dark"][data-contrast="more"] {\n  --accent-text: ${c.darkHC.accentText.toLowerCase()};\n}\n`;
  for (const slug of Object.keys(sets).filter((s) => s !== "sirkov")) {
    for (const theme of ["dark", "light"]) {
      const sel =
        theme === "dark"
          ? `[data-theme="dark"][data-accent="${slug}"],\n:root:not([data-theme])[data-accent="${slug}"]`
          : `[data-theme="light"][data-accent="${slug}"]`;
      css += `${sel} {\n${accentLines(sets[slug][theme])}\n}\n`;
    }
  }
  css += `\n/* The whole palette — only for AccentPicker and «Авто» */\n`;
  for (const theme of ["dark", "light"]) {
    css += `${theme === "dark" ? `:root,\n[data-theme="dark"]` : `[data-theme="light"]`} {\n`;
    for (const slug of Object.keys(sets)) {
      const s = sets[slug][theme];
      css += `  --accent-${slug}-fill: ${s.accentFill};\n  --accent-${slug}-on: ${s.accentOn};\n`;
    }
    css += `}\n`;
  }
  css += `\n/* Text styles of DESIGN.md §2 \`type.styles\`; the rest are in extra.css */\n`;
  css +=
    style("hero", "t-hero") +
    style("pageTitle", "t-page-title") +
    style("shelfTitle", "t-shelf-title");
  css += style("body", "t-body") + style("badge", "t-badge");
  css += `.t-badge {\n  text-transform: uppercase;\n  letter-spacing: 0.06em;\n}\n`;
  css += `.tabular {\n  font-variant-numeric: tabular-nums;\n}\n`;
  css += `html {\n  font-family: var(--font-sans);\n  font-variation-settings:\n    "CRSV" 0,\n    "SHRP" 0;\n}\n`;

  const ts = `// GENERATED by scripts/gen-tokens.mjs from DESIGN.md (T9.1). Do not edit.
export const COLOR = ${JSON.stringify(
    { light: c.light, dark: c.dark, lightHC: c.lightHC, darkHC: c.darkHC },
    null,
    2,
  )} as const;

/** Surfaces an accent must work on, per theme (bg, surface, raised, flyout). */
export const BACKGROUNDS = ${JSON.stringify(ctx.backgrounds, null, 2)} as const;
export const INK_DARK = ${JSON.stringify(ctx.inkDark)};
export const INK_LIGHT = ${JSON.stringify(ctx.inkLight)};

/** The 17 colour sets × 2 themes (sirkov = #650A12 from the tokens). */
export const ACCENT_SETS: Record<
  string,
  Record<"dark" | "light", { accentFill: string; accentText: string; accentOn: string }>
> = ${JSON.stringify(sets, null, 2)};
`;
  return { css, ts };
}

export function run() {
  const { css, ts } = build(readFileSync(DESIGN, "utf8"), JSON.parse(readFileSync(SEEDS, "utf8")));
  writeFileSync(OUT_CSS, css);
  writeFileSync(OUT_TS, ts);
  return { css, ts };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  run();
  console.log("tokens: sirtone.css + tokens.generated.ts written");
}
