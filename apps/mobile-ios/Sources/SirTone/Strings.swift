    /// `key.one` / `key.few` / `key.many` with `%d`.
    static func count(_ key: String, _ n: Int) -> String {
        let m10 = n % 10, m100 = n % 100
        let form = m10 == 1 && m100 != 11 ? "one"
            : (2...4).contains(m10) && !(12...14).contains(m100) ? "few" : "many"
        return t("\(key).\(form)", n)
    }

